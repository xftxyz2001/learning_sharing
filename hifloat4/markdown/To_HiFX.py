import numpy as np

def To_HiFX(x, N = 4, M=2, G = 64): 
    """
    HiF4 / HiF5 量化主函数：将输入浮点张量转为 HiFX 格式（三级指数块浮点）
    核心架构：{E6M2 全局缩放 + 8组1bit指数 + 16组1bit指数} + S1P2 尾数
    按列（通道/特征维度）进行分组量化
    
    参数说明：
    x: 输入浮点张量（一般为激活/权重）
    N: 尾数精度，HiF4固定N=4，HiF5=N=5
    M: E6M2的尾数位，固定M=2
    G: 组大小，固定64个元素一组
    """

    # ======================== 格式常量定义（硬件级固定） ========================
    # E6M2：6位指数+2位尾数，偏移48 → 表示范围 2^[-48, 15] × 1.M2
    # E6M2 最大值：2^15 × 1.5 = 49152
    # E6M2 最小值：2^(-48)
    # 二级+三级指数 + S1P2 能表示的最大值：2^2 × 1.75 = 7
    # HiF4: N=4, G=64
    # HiF5: N=5, G=64

    # ======================== 1. 输入张量形状初始化 ========================
    x = np.array(x)             # 转为numpy数组
    Mi = x.shape[0]            # 行数（特征维度/空间维度）
    Ni = x.shape[1]            # 列数（通道维度）
    Mcnt = np.ceil(Mi/G).astype(int)  # 一共多少个64元素组（向上取整）

    # ======================== 2. 输出/中间变量开辟 ========================
    res    = np.zeros((Mi,     Ni))  # 最终量化反量化后的输出张量（HiF4/5）
    GE6M2  = np.zeros((Mcnt,   Ni))  # 一级缩放因子：E6M2（每组64一个）
    GE1_8  = np.zeros((Mcnt*8, Ni))  # 二级指数：8个1bit（每组64里分8小组）
    GE1_16 = np.zeros((Mcnt*16,Ni))  # 三级指数：16个1bit（每组64里分16小组）
    GDE16  = np.zeros((Mcnt*16,Ni))  # 二级+三级合并指数
    Sign   = np.zeros((Mi,     Ni))  # 每个元素的符号位
    igpA   = np.zeros((Mi,     Ni))  # 组内归一化后的绝对值（S1P2域）
    VmaxS  = np.zeros((Mcnt,   Ni))  # 组内最大值经过一级缩放后的值
    
    Ng = N - 2  # 尾数位偏移：HiF4=4-2=2，HiF5=5-2=3

    # ======================== 3. 逐组、逐列量化 ========================
    for i in range(Mcnt):          # 遍历所有64元素组
        for j in range(Ni):        # 按列处理（每列独立量化）
            # --------------------- 取出当前64元素一组 ---------------------
            ori = x[i*G:i*G+G,j]   # 取第i组、第j列的64个值
            G_size = len(ori)      # 实际长度（不足64时自动适配）

            # --------------------- 提取符号位 ---------------------
            S = np.ones(G)        # 符号数组，默认正
            S[ori < 0] = -1       # 负数设为-1
            S = S.T
            tmpG = np.abs(ori)    # 取绝对值（量化只处理正数）

            # --------------------- 三级最大值提取（硬件并行） ---------------------
            # 64 → 16个max：每4个元素取一个最大值（16个值）
            V16 = np.zeros(16, dtype=np.float32)
            for k in range(16):
                V16[k] = np.max(tmpG[k*4:k*4+4])

            # 16 → 8个max：每2个V16取一个最大值（8个值）
            V8 = np.zeros(8, dtype=np.float32)
            for k in range(8):
                V8[k] = np.max(V16[k*2:k*2+2])            

            # 8 → 1个全局最大值（整组64的最大值）
            Vmax = np.max(V8)

            # ======================== 4. 一级缩放：E6M2 全局缩放因子 ========================
            # 核心：将组最大值缩放到 HiFX 组内上限 7
            Const_rec = To_BF16(1 / 7.00)    # 1/7 常数（BF16精度）
            SF = Vmax * Const_rec            # 缩放因子 = 组最大值 / 7
            SF = To_BF16(SF)                 # 转为BF16
            E6M2 = BF16_to_E6MX(SF, M=M)     # BF16 → E6M2 格式存储

            # ======================== 5. 二级指数：8个1bit 细粒度缩放 ========================
            REC_E6M2 = To_BF16(1 / E6M2)     # 一级缩放的倒数（归一化用）
            # 判断：归一化后的值 ≥4 → 二级指数=1，否则=0
            E1_8 = (V8 * REC_E6M2) >= 4      # 输出0/1二值

            # ======================== 6. 三级指数：16个1bit 更细粒度缩放 ========================
            # 把二级8个指数广播成16个（每个对应三级分组）
            E1_8x2 = np.zeros(16, dtype=np.float32)
            for k in range(8):
                E1_8x2[k*2:k*2+2] = E1_8[k]         

            # 判断：归一化后再经二级缩放后 ≥2 → 三级指数=1
            E1_16 = (V16 * REC_E6M2 * 2 ** (-E1_8x2)) >= 2  

            # ======================== 7. 合并指数 + 组内归一化量化 ========================
            DE16 = E1_16 + E1_8x2        # 合并二级+三级指数（0/1/2）

            # 把16组合并指数广播到64个元素
            DE64 = np.zeros(G, dtype=np.float32)                
            for k in range(16):
                DE64[k*4:k*4+4] = DE16[k]

            # 归一化到 S1P2 域（0~2 区间）
            in_grp = tmpG * REC_E6M2 * 2 ** (-DE64 + Ng) 
            in_grp = np.floor(in_grp + 0.5)               # 四舍五入
            in_grp = in_grp * 2.0 ** (-Ng)                # 恢复尾数精度

            # 溢出截断：最大值限制为 2 - 2^(-Ng)
            in_grp[in_grp >= 2] = 2 - 2**(-Ng)

            # ======================== 8. 反量化恢复数值 ========================
            # 量化值 = E6M2 × 2^合并指数 × 组内归一化值 × 符号
            grp = E6M2 * (2.0 ** DE64) * in_grp
            grp = grp * S

            # ======================== 9. 写入结果 ========================
            res[i*G:i*G+G, j] = grp

    return res